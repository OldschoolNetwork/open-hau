let pending: Promise<void> | undefined;
export function loadMacSymbols() {
  if (!isTauri()) return Promise.resolve();
  return (pending ??= invoke<Record<string, string>>("macos_symbols", {
    names: [...new Set(Object.values(symbolNames))],
  })
    .then((images) => {
      macSymbols.set(images);
    })
    .catch((error) => {
      pending = undefined;
      console.warn("System symbols unavailable:", error);
    }));
}
